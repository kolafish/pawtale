"""Shared naming policy for memoir chapters and sections, including voice edits."""
from typing import Literal


_TITLE_STYLE = """标题命名要求（仅适用于本次允许新拟或改写的章名、小节名）：
- 标题应自然、朴素，有生活气息，像真实回忆录中的章节名，而不是内容分类或主题概括。
- 自然生动：优先从具体的人物、事件、场景和细节中提炼标题，让人读后有兴趣继续看。
- 适度文学化：可以有画面感、故事感或生活中的幽默，但不刻意煽情、不堆砌修辞、不故作深沉。
- 避免刻板套路：避免“某某的……与……”“某某的早年经历与家庭生活”等分类式、报告式标题，不罗列主题；不机械禁止“与”字或人物称谓。
- 简洁有辨识度：抓住最有特色的故事或细节，不求概括全部内容，不虚构、不拔高，不用贬损性评价代替故事。
- 命名时优先考虑“这段故事中，什么最值得读者记住”，而不是“这段内容属于什么主题”。
- 人物、事件、细节和情绪必须有内容依据；年龄、年份或人生阶段不明时不推断，不用记录日期代替事件时间。
- 沿用正文或讲述的叙述视角，不使用“讲述者”“叙述者”等内部称呼，不补原文没有的场景、对白或寓意。
- 用户明确指定的新标题按原意采用，不因命名风格另拟；只要求纠正标题中的错字或名称时，仅作对应更正。
- 命名规则不授权额外改名：未涉及的标题、人工保护及各入口的编辑范围保持不变。
"""
_CHAPTER_SCOPE = "章标题：理解全章内容后，选择最能代表这一组经历的人物、生活场景或故事线索命名，可以有一定概括性，但不罗列各小节主题。可以用有代表性的具体细节作题眼，但不能让读者误以为全章只讲一个局部事件。"
_SECTION_SCOPE = "小节标题：更贴近本节具体发生的事，优先抓住一个有辨识度的事件、动作、场景或细节，不必概括本节全部内容，也不反复复述章名。"


def title_naming_guidance(level: Literal["chapter", "section", "both"]) -> str:
    scope = {
        "chapter": _CHAPTER_SCOPE,
        "section": _SECTION_SCOPE,
        "both": _CHAPTER_SCOPE + "\n" + _SECTION_SCOPE,
    }[level]
    return _TITLE_STYLE + scope + "\n"
